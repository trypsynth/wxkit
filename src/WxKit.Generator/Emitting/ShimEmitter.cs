using WxKit.Generator.Binding;

namespace WxKit.Generator.Emitting;

// Writes the shim's generated C interface: a header of declarations, which wxkit.h includes, and
// the C++ that implements them.
internal static class ShimEmitter {
	public const string Banner = "// <auto-generated> Written by scripts/generate.ps1 from the wxWidgets interface headers. Do not edit. </auto-generated>";

	// The preprocessor symbol each wxWidgets port defines, for functions that exist on only some.
	private static readonly Dictionary<string, string> Ports = new(StringComparer.Ordinal) {
		["wxmsw"] = "__WXMSW__",
		["wxgtk"] = "__WXGTK__",
		["wxosx"] = "__WXOSX__",
		["wxqt"] = "__WXQT__",
		["wxx11"] = "__WXX11__",
		["wxuniv"] = "__WXUNIVERSAL__",
	};

	public static string Header(BindingResult result) {
		CodeWriter writer = new();
		writer.Line(Banner).Line("#pragma once").Line();
		List<BoundClass> plain = [.. result.Classes.Where(static bound => !bound.Tweak.IsHandwritten && bound.Handle.IsPlain)];
		if (plain.Count > 0) {
			writer.Line("// Classes that aren't wxObjects, each a handle of its own type").Line();
			foreach (BoundClass bound in plain) writer.Line($"typedef struct {bound.Handle.CType} {bound.Handle.CType};");
			writer.Line();
		}
		if (HasDirectors(result)) {
			writer.Line("// Called with a director's userdata when the director is deleted.").Line();
			writer.Line(OnFreeSignature + " WXK_NOEXCEPT;").Line();
		}
		foreach (BoundClass bound in result.Classes) {
			List<BoundFunction> functions = [.. bound.Functions];
			if (functions.Count == 0) continue;
			writer.Line($"// {bound.CppName}").Line();
			foreach (BoundFunction function in functions) writer.Line(Signature(function) + " WXK_NOEXCEPT;");
			if (HasDelete(bound)) writer.Line(DeleteSignature(bound) + " WXK_NOEXCEPT;");
			if (bound.Directors.Count > 0) writer.Line(SetDirectorsSignature(bound) + " WXK_NOEXCEPT;");
			writer.Line();
		}
		writer.Line("// Event types").Line();
		foreach (BoundEventType type in result.EventTypes) writer.Line($"WXK_FUNCTION(int32_t) wxk_EventType_{type.Name}(void) WXK_NOEXCEPT;");
		return writer.ToString();
	}

	// The shim's C++, in a file for each class. A linker loads an object file of a static library
	// whole, and with it every wxWidgets object file any of its functions refers to, even functions
	// it then leaves out, so one file for every class would bring every class's wxWidgets code into
	// every application. Event types are in a file for each header, as their constants are in
	// wxWidgets's object files for it. Every file includes every header, which links nothing.
	public static IEnumerable<(string FileName, string Text)> Files(BindingResult result) {
		yield return ("includes.h", Includes(result));
		yield return ("checks.cpp", Checks(result));
		if (HasDirectors(result)) {
			yield return ("directors.h", DirectorDeclarations(result));
			yield return ("Directors.cpp", DirectorsFile());
		}
		foreach (BoundClass bound in result.Classes.Where(static bound => bound.Functions.Any())) yield return ($"{bound.Name}.cpp", ClassFile(bound));
		foreach (IGrouping<string, BoundEventType> group in result.EventTypes.GroupBy(static type => type.Header ?? "wx/event.h").OrderBy(static group => group.Key, StringComparer.Ordinal)) {
			string name = group.Key.Replace("wx/", string.Empty, StringComparison.Ordinal).Replace(".h", string.Empty, StringComparison.Ordinal).Replace('/', '_');
			yield return ($"EventTypes_{name}.cpp", EventTypeFile(group));
		}
	}

	private static string Includes(BindingResult result) {
		CodeWriter writer = new();
		writer.Line(Banner).Line("#pragma once").Line().Line("#include \"../src/shim.h\"").Line();
		IEnumerable<string?> headers = result.Classes.Select(static bound => bound.Source.Header).Concat(result.EventTypes.Select(static type => type.Header));
		foreach (string header in headers.OfType<string>().Distinct().Order(StringComparer.Ordinal)) writer.Line($"#include <{header}>");
		// A class that isn't a wxObject converts to and from its handle here, so every file that takes one can.
		foreach (BoundClass bound in result.Classes.Where(static bound => bound.Handle.IsPlain && bound.Handle.CppBase == bound.CppName)) {
			writer.Line();
			if (bound.Tweak.ClassGuard is string guard) writer.Line($"#if {guard}");
			writer.Line("namespace wxk {");
			writer.Line($"inline {bound.CppName}* Unwrap({bound.Handle.CType}* value) {{ return reinterpret_cast<{bound.CppName}*>(value); }}");
			writer.Line($"inline {bound.Handle.CType}* Wrap({bound.CppName}* value) {{ return reinterpret_cast<{bound.Handle.CType}*>(value); }}");
			writer.Line("} // namespace wxk");
			if (bound.Tweak.ClassGuard is not null) writer.Line("#endif");
		}
		return writer.ToString();
	}

	// The managed enums hold the values the generator worked out from the headers. These checks
	// fail the native build if one of them is not what the C++ constant is. Each is compared as the
	// type the shim passes it as: enums as 32-bit ints, so wxOBJID_SYSMENU, 0xFFFFFFFF, matches -1,
	// and styles as longs, so wxVSCROLL, (int)0x80000000, matches 0x80000000.
	private static string Checks(BindingResult result) {
		CodeWriter writer = new();
		writer.Line(Banner).Line("#include \"includes.h\"").Line();
		// An enum that wxWidgets only declares under a condition, such as the accessibility ones under
		// wxUSE_ACCESSIBILITY, is only checked under it.
		IEnumerable<(BoundStyle Value, string Type, string? Guard)> values = result.Enums.SelectMany(static bound => bound.Members.Select(value => (value, "int32_t", bound.Guard))).Concat(result.Classes.SelectMany(static bound => bound.Styles?.Members ?? []).Select(static value => (value, "long", (string?)null)));
		foreach (IGrouping<string?, (BoundStyle Value, string Type, string? Guard)> group in values.Where(static entry => entry.Value.Constant.StartsWith("wx", StringComparison.Ordinal) || entry.Value.Constant.StartsWith("WX", StringComparison.Ordinal)).DistinctBy(static entry => entry.Value.Constant).GroupBy(static entry => entry.Guard).OrderBy(static group => group.Key ?? string.Empty, StringComparer.Ordinal)) {
			if (group.Key is string guard) writer.Line().Line($"#if {guard}");
			foreach ((BoundStyle value, string type, _) in group.OrderBy(static entry => entry.Value.Constant, StringComparer.Ordinal)) {
				writer.Line($"static_assert(static_cast<{type}>({value.Constant}) == static_cast<{type}>({value.Value}LL), \"{value.Constant} is not {value.Value}\");");
			}
			if (group.Key is not null) writer.Line("#endif");
		}
		return writer.ToString();
	}

	// The callbacks of a class's overridable members, which the directors of the classes derived
	// from it call too.
	private static string DirectorDeclarations(BindingResult result) {
		CodeWriter writer = new();
		writer.Line(Banner).Line("#pragma once").Line().Line("#include \"includes.h\"").Line().Line("#include <utility>").Line();
		writer.Line("namespace wxk::directors {").Line();
		writer.Line("// Tells .NET a director is gone, with the userdata it was made with, which isn't null.");
		writer.Line("extern void (*onFree)(void* userdata);").Line();
		foreach (BoundClass bound in result.Classes.Where(static bound => bound.Directors.Count > 0)) {
			writer.Line($"// {bound.CppName}'s overridable members call into .NET through these, once it sets them.");
			foreach (BoundFunction director in bound.Directors) writer.Line($"extern {CallbackPointer(director, CallbackName(director))};");
			writer.Line();
			// Every director made from the class gives its own implementation of each member through
			// this, which the managed default calls. A base call reaches it with dynamic_cast, which
			// C++ checks, rather than casting the object to a class it isn't.
			if (!HasBaseInterface(bound)) continue;
			writer.Line($"// What {bound.CppName}'s own members do, which each director made from it gives.");
			writer.Open($"struct {BaseInterface(bound)}");
			foreach (BoundFunction director in bound.Directors.Where(static director => director.HasBaseExport)) writer.Line($"virtual {director.Source.Type} Base{director.Source.Name}({Parameters(director)}){Constness(director)} = 0;");
			writer.Line().Line("protected:");
			writer.Line($"~{BaseInterface(bound)}() = default;");
			writer.Close("};").Line();
		}
		writer.Line("} // namespace wxk::directors");
		return writer.ToString();
	}

	private static string ClassFile(BoundClass bound) {
		CodeWriter writer = new();
		writer.Line(Banner).Line(bound.HasDirector || bound.Directors.Count > 0 ? "#include \"directors.h\"" : "#include \"includes.h\"").Line();
		// The callbacks are C, so they're there even where the class isn't, as SetDirectors sets them.
		if (bound.Directors.Count > 0) {
			writer.Line("namespace wxk::directors {").Line();
			foreach (BoundFunction director in bound.Directors) writer.Line($"{CallbackPointer(director, CallbackName(director))} = nullptr;");
			writer.Line().Line("} // namespace wxk::directors").Line();
		}
		if (bound.Tweak.ClassGuard is string classGuard) writer.Line($"#if {classGuard}").Line();
		if (bound.Directors.Count > 0 || bound.HasDirector) {
			writer.Line("namespace {").Line();
			WriteDirectors(writer, bound);
			writer.Line("} // namespace").Line();
		}
		if (bound.Tweak.ClassGuard is not null) writer.Line("#endif").Line();
		foreach (BoundFunction function in bound.Functions) {
			WriteFunction(writer, function);
			writer.Line();
		}
		if (bound.Directors.Count > 0) {
			writer.Open(SetDirectorsSignature(bound) + " noexcept");
			foreach (BoundFunction director in bound.Directors) writer.Line($"wxk::directors::{CallbackName(director)} = {Camel(director.Source.Name)};");
			writer.Close();
		}
		if (HasDelete(bound)) {
			writer.Open(DeleteSignature(bound) + " noexcept");
			writer.Line("wxk::Guard([&] { delete wxk::Unwrap(self); });");
			writer.Close();
		}
		return writer.ToString();
	}

	private static string EventTypeFile(IEnumerable<BoundEventType> types) {
		CodeWriter writer = new();
		writer.Line(Banner).Line("#include \"includes.h\"").Line();
		foreach (BoundEventType type in types) {
			writer.Open($"WXK_FUNCTION(int32_t) wxk_EventType_{type.Name}(void) noexcept");
			writer.Line($"return {type.Constant};");
			writer.Close().Line();
		}
		return writer.ToString();
	}

	// A director is a subclass WxKit creates instead of a class, whose overridable members call
	// into .NET through callbacks it sets once, or the class's own when it has not. A struct that
	// derives from the class that declares them calls the class's own, since they are often
	// protected, for the managed defaults.
	private static void WriteDirectors(CodeWriter writer, BoundClass bound) {
		if (HasBaseInterface(bound)) {
			writer.Open($"struct {Access(bound)}");
			foreach (BoundFunction director in bound.Directors.Where(static director => director.HasBaseExport)) {
				string constness = director.Source.IsConst ? "const " : string.Empty;
				writer.Open($"static {director.Source.Type} {director.Source.Name}({constness}{bound.CppName}* self{string.Concat(director.Source.Parameters.Select(static parameter => $", {parameter.Type} {parameter.Name}"))})");
				writer.Line($"auto* base = dynamic_cast<{constness}wxk::directors::{BaseInterface(bound)}*>(self);");
				writer.Line($"if (base == nullptr) throw std::logic_error(\"Only a {bound.CppName} WxKit made can call its own {director.Source.Name}.\");");
				writer.Line($"return base->Base{director.Source.Name}({Arguments(director)});");
				writer.Close();
			}
			writer.Close("};").Line();
		}
		if (!bound.HasDirector) return;
		// The director derives from the class first, so its handle is the class's, and then from the
		// base interface of each class whose overridable members it has.
		List<BoundClass> declaring = [.. bound.AllDirectors.Select(static director => director.Owner).Distinct().Where(HasBaseInterface)];
		writer.Open($"struct {Director(bound)} final : {string.Join(", ", declaring.Select(static owner => $"wxk::directors::{BaseInterface(owner)}").Prepend(bound.CppName))}");
		writer.Line("template <typename... Arguments>");
		writer.Line($"explicit {Director(bound)}(void* userdata, Arguments&&... arguments) : {bound.CppName}(std::forward<Arguments>(arguments)...), _userdata(userdata) {{}}");
		writer.Line();
		writer.Line($"{Director(bound)}(const {Director(bound)}&) = delete;");
		writer.Line($"{Director(bound)}& operator=(const {Director(bound)}&) = delete;");
		writer.Line();
		writer.Open($"~{Director(bound)}() override");
		writer.Line("if (_userdata != nullptr && wxk::directors::onFree != nullptr) wxk::directors::onFree(_userdata);");
		writer.Close();
		foreach (BoundFunction director in bound.AllDirectors.Where(static director => director.HasBaseExport)) {
			writer.Line();
			writer.Open($"{director.Source.Type} Base{director.Source.Name}({Parameters(director)}){Constness(director)} override");
			writer.Line($"return {bound.CppName}::{director.Source.Name}({Arguments(director)});");
			writer.Close();
		}
		foreach (BoundFunction director in bound.AllDirectors) {
			writer.Line();
			string parameters = string.Join(", ", director.Source.Parameters.Select(static parameter => $"{parameter.Type} {parameter.Name}"));
			writer.Open($"{director.Source.Type} {director.Source.Name}({parameters}){(director.Source.IsConst ? " const" : string.Empty)} override");
			string callback = $"wxk::directors::{CallbackName(director)}";
			string own = $"{bound.CppName}::{director.Source.Name}({Arguments(director)})";
			string self = $"wxk::Wrap(static_cast<{bound.Handle.CppBase}*>(const_cast<{Director(bound)}*>(this)))";
			string call = $"{callback}({string.Join(", ", director.Parameters.Select(static parameter => parameter.Conversion.ToCallbackArgument(parameter.CppName)).Prepend("_userdata").Prepend(self))})";
			bool isVoid = director.Returns is VoidConversion;
			ClassTweak tweak = director.Owner.Tweak;
			if (tweak.DirectorsBeforeBase.Contains(director.Source.Name)) {
				writer.Line($"if ({callback} != nullptr) {call};");
				writer.Line($"{own};");
			} else if (tweak.DirectorsAfterBase.Contains(director.Source.Name)) {
				if (isVoid) {
					writer.Line($"{own};");
					writer.Line($"if ({callback} != nullptr) {call};");
				} else {
					writer.Line($"if (!{own}) return false;");
					writer.Line($"if ({callback} == nullptr) return true;");
					writer.Line($"return {director.Returns.FromCallback(call)};");
				}
			} else {
				// A pure virtual member has nothing of its own to fall back on, so gives nothing.
				string fallback = !director.Source.IsPureVirtual ? $"return {own};" : isVoid ? "return;" : "return {};";
				writer.Line($"if ({callback} == nullptr) {fallback}");
				writer.Line(isVoid ? $"{call};" : $"return {director.Returns.FromCallback(call)};");
			}
			writer.Close();
		}
		writer.Line().Line("private:");
		writer.Line("void* _userdata;");
		writer.Close("};").Line();
	}

	private static string Access(BoundClass bound) => Naming.Type(bound.CppName) + "Access";

	// A class that isn't a wxObject, which .NET makes, the shim also deletes.
	internal static bool HasDelete(BoundClass bound) => bound.Handle.IsPlain && bound.Constructors.Count > 0;

	private static string DeleteSignature(BoundClass bound) => $"WXK_FUNCTION(void) wxk_{Naming.Type(bound.CppName)}_delete({bound.Handle.CType}* self)";

	private static string BaseInterface(BoundClass bound) => Naming.Type(bound.CppName) + "Base";

	private static bool HasBaseInterface(BoundClass bound) => bound.Directors.Any(static director => director.HasBaseExport);

	private static bool HasDirectors(BindingResult result) => result.Classes.Any(static bound => bound.Directors.Count > 0);

	private const string OnFreeSignature = "WXK_FUNCTION(void) wxk_Directors_SetOnFree(void (*onFree)(void* userdata))";

	private static string DirectorsFile() {
		CodeWriter writer = new();
		writer.Line(Banner).Line("#include \"directors.h\"").Line();
		writer.Line("namespace wxk::directors {").Line();
		writer.Line("void (*onFree)(void* userdata) = nullptr;").Line();
		writer.Line("} // namespace wxk::directors").Line();
		writer.Open(OnFreeSignature + " noexcept");
		writer.Line("wxk::directors::onFree = onFree;");
		writer.Close();
		return writer.ToString();
	}

	private static string Parameters(BoundFunction director) => string.Join(", ", director.Source.Parameters.Select(static parameter => $"{parameter.Type} {parameter.Name}"));

	private static string Constness(BoundFunction director) => director.Source.IsConst ? " const" : string.Empty;

	private static string Director(BoundClass bound) => Naming.Type(bound.CppName) + "Director";

	private static string CallbackName(BoundFunction director) => $"{Naming.Type(director.Owner.CppName)}_{director.Source.Name}";

	private static string Camel(string name) => char.ToLowerInvariant(name[0]) + name[1..];

	private static string Arguments(BoundFunction director) => string.Join(", ", director.Source.Parameters.Select(static parameter => parameter.Name));

	// A callback takes the object, then each parameter as C++ hands it out.
	private static string CallbackPointer(BoundFunction director, string name) {
		IEnumerable<string> parameters = director.Parameters.Select(static parameter => $"{parameter.Conversion.CallbackParameterCType} {parameter.CppName}").Prepend("void* userdata").Prepend($"{director.Owner.Handle.CType}* self");
		return $"{director.Returns.CallbackCType} (*{name})({string.Join(", ", parameters)})";
	}

	private static string SetDirectorsSignature(BoundClass bound) => $"WXK_FUNCTION(void) wxk_{Naming.Type(bound.CppName)}_SetDirectors({string.Join(", ", bound.Directors.Select(static director => CallbackPointer(director, Camel(director.Source.Name))))})";

	private static string Signature(BoundFunction function) {
		BoundClass owner = function.Owner;
		List<string> parameters = [];
		if (!function.IsConstructor && !function.IsStatic) parameters.Add($"{owner.Handle.CType}* self");
		if (function.TakesUserdata) parameters.Add("void* userdata");
		parameters.AddRange(function.Parameters.SelectMany(static parameter => parameter.Conversion.CParameters(parameter.Name.TrimStart('@'))));
		string returns = function.IsConstructor ? $"{owner.Handle.CType}*" : function.Returns.CReturnType;
		return $"WXK_FUNCTION({returns}) {function.ShimName}({(parameters.Count == 0 ? "void" : string.Join(", ", parameters))})";
	}

	private static void WriteFunction(CodeWriter writer, BoundFunction function) {
		BoundClass owner = function.Owner;
		List<string> argumentList = [.. function.Parameters.Select(static parameter => parameter.Conversion.ToCpp(parameter.Name.TrimStart('@')))];
		foreach ((int index, string argument) in function.FilledArguments) argumentList.Insert(index, argument);
		string arguments = string.Join(", ", argumentList);
		string returns = function.IsConstructor ? $"{owner.Handle.CType}*" : function.Returns.CReturnType;
		string fallback = function.IsConstructor ? "nullptr" : function.Returns.Fallback;
		writer.Open(Signature(function).Replace(" WXK_NOEXCEPT", string.Empty) + " noexcept");
		string? ports = function.OnlyFor.Count == 0 ? null : string.Join(" || ", function.OnlyFor.Select(static port => Ports.TryGetValue(port, out string? symbol) ? $"defined({symbol})" : "0"));
		string? feature = owner.Tweak.MemberGuards.GetValueOrDefault(function.Source.Name) ?? owner.Tweak.OverloadGuards.FirstOrDefault(guard => guard.Matches(function.Source))?.Condition;
		string[] conditions = [.. new[] { ports, feature, owner.Tweak.ClassGuard }.OfType<string>()];
		string? guard = conditions.Length switch {
			0 => null,
			1 => conditions[0],
			_ => string.Join(" && ", conditions.Select(static condition => $"({condition})")),
		};
		if (guard is not null) writer.Line($"#if {guard}");
		if (function.IsConstructor) {
			writer.Open($"return wxk::Guard<{returns}>(nullptr, [&]");
			string made = owner.HasDirector ? $"{Director(owner)}({string.Join(", ", new[] { "userdata", arguments }.Where(static part => part.Length > 0))})" : $"{owner.CppName}({arguments})";
			writer.Line($"{owner.Handle.CppBase}* created = new {made};");
			writer.Line("return wxk::Wrap(created);");
			writer.Close("});");
		} else {
			// A mixin's member is called through the mixin, which picks it out when two mixins both
			// have one, as wxTextEntry and wxItemContainer both have IsEmpty, and still calls overrides.
			string target = $"static_cast<{owner.CppName}*>(wxk::Unwrap(self))";
			string? mixin = function.Source.Mixin is string named ? owner.Tweak.MixinBases.GetValueOrDefault(named) ?? named : null;
			if (mixin is not null) target = $"static_cast<{mixin}*>({target})";
			string call = function.IsStatic ? $"{(owner.Tweak.IsGlobal ? string.Empty : mixin ?? owner.CppName)}::{function.Source.Name}({arguments})" : $"{target}->{function.Source.Name}({arguments})";
			if (function.IsDirectorBase) call = $"{Access(owner)}::{function.Source.Name}({string.Join(", ", function.Parameters.Select(static parameter => parameter.Conversion.ToCpp(parameter.Name.TrimStart('@'))).Prepend(target))})";
			if (function.Returns is VoidConversion or SelfConversion) {
				writer.Line($"wxk::Guard([&] {{ {call}; }});");
			} else {
				writer.Line($"return wxk::Guard<{returns}>({fallback}, [&]() -> {returns} {{ return {function.Returns.FromCpp(call)}; }});");
			}
		}
		if (guard is not null) {
			// A function the port lacks still exists, so an application that links statically never
			// misses a symbol. It does nothing, and returns the function's "nothing" value.
			writer.Line("#else");
			if (!function.IsConstructor && !function.IsStatic) writer.Line("(void)self;");
			foreach (BoundParameter parameter in function.Parameters) {
				foreach (string declaration in parameter.Conversion.CParameters(parameter.Name.TrimStart('@'))) writer.Line($"(void){declaration.Split(' ')[^1]};");
			}
			if (returns != "void") writer.Line($"return {fallback};");
			writer.Line("#endif");
		}
		writer.Close();
	}
}
