using WxKit.Generator.Binding;

namespace WxKit.Generator.Emitting;

// Writes the managed API: a partial class for each bound class, the event types, the style enums,
// and the table that lets WxKit wrap native objects it did not create. Hand-written partials sit
// beside the generated ones and add what the generator cannot know.
internal static class ManagedEmitter {
	// Code marked as generated has nullable annotations off unless it turns them back on.
	public const string Banner = "// <auto-generated> Written by scripts/generate.ps1 from the wxWidgets interface headers. Do not edit. </auto-generated>\n#nullable enable";

	public static IEnumerable<(string FileName, string Text)> Files(BindingResult result) {
		foreach (BoundClass bound in result.Classes.Where(static bound => !bound.Tweak.IsHandwritten && !bound.Tweak.IsInteropOnly)) yield return ($"{bound.Name}.g.cs", Class(bound));
		yield return ("EventType.g.cs", EventTypes(result));
		yield return ("Styles.g.cs", Styles(result));
		yield return ("Enums.g.cs", Enums(result));
		foreach (BoundEnum constants in result.Enums.Where(static bound => bound.IsConstantClass)) yield return ($"{constants.Name}.g.cs", ConstantClass(constants));
		yield return ("ArtIds.g.cs", ArtIds(result));
		yield return ("ObjectRegistry.g.cs", Factories(result));
	}

	private static CodeWriter Start() => new CodeWriter().Line(Banner).Line("using WxKit.Interop;").Line().Line("namespace WxKit;").Line();

	private static string Class(BoundClass bound) {
		CodeWriter writer = Start();
		Summary(writer, $"{Sentence(bound.Source.Brief)}Wraps {bound.CppName}.");
		string baseList = bound.Base is not null ? " : " + bound.Base.Name : bound.Handle.IsOwned ? " : NativeObject" : string.Empty;
		writer.Open(bound.Handle == HandleKind.Static ? $"public static unsafe partial class {bound.Name}" : $"public unsafe partial class {bound.Name}{baseList}");
		bool first = true;
		void Gap() {
			if (!first) writer.Line();
			first = false;
		}
		foreach (BoundFunction constructor in bound.Constructors) {
			Gap();
			Summary(writer, constructor.Source.Brief);
			string arguments = string.Join(", ", constructor.ManagedParameters.Select(static parameter => parameter.Name));
			writer.Open($"public {bound.Name}({ParameterList(constructor.ManagedParameters, withDefaults: true)}) : this(CreateNative({arguments}))");
			// A parameter the native object goes on using stays alive as long as this object does.
			foreach (BoundParameter kept in constructor.ManagedParameters.Where(parameter => bound.Tweak.KeptAlive.Contains(parameter.CppName))) writer.Line($"KeepAlive({kept.Name});");
			writer.Close();
		}
		if (bound.Handle == HandleKind.Owned) {
			Gap();
			writer.Open($"internal {bound.Name}(WxkObject* native) : base(native)").Close();
		} else if (bound.Handle == HandleKind.Value) {
			Gap();
			writer.Open($"internal {bound.Name}(WxkObject* native) : base(native)").Close();
			writer.Line();
			writer.Line("// Takes ownership of a copy the shim hands out, which is null when the value was empty.");
			writer.Line($"internal static {(bound.Base is null ? string.Empty : "new ")}{bound.Name}? Take(WxkObject* native) => native is null ? null : new {bound.Name}(native);");
		} else if (bound.Base is not null && bound.Handle != HandleKind.Static) {
			Gap();
			// A base with another kind of handle, such as EvtHandler under Window, takes it as its own kind.
			string handle = bound.Base.Handle == bound.Handle ? "native" : $"({bound.Base.Handle.InteropType}*)native";
			writer.Open($"internal {bound.Name}({bound.Handle.InteropType}* native) : base({handle})").Close();
		}
		foreach (BoundProperty property in bound.Properties.OrderBy(static property => property.Name, StringComparer.Ordinal)) {
			Gap();
			WriteProperty(writer, bound, property);
		}
		foreach (BoundEvent boundEvent in bound.Events.OrderBy(static boundEvent => boundEvent.Name, StringComparer.Ordinal)) {
			Gap();
			Summary(writer, boundEvent.Description);
			string type = $"EventType.{boundEvent.Type.Name}";
			writer.Open($"public event EventHandler<{boundEvent.Type.EventClass.Name}>? {boundEvent.Name}");
			writer.Line($"add => AddHandler({type}, StandardId.Any, StandardId.Any, value, this);");
			writer.Line($"remove => RemoveHandler({type}, StandardId.Any, StandardId.Any, value);");
			writer.Close();
		}
		foreach (BoundMethod method in bound.Methods.OrderBy(static method => method.Name, StringComparer.Ordinal)) {
			Gap();
			WriteMethod(writer, bound, method);
		}
		foreach (BoundFunction director in bound.Directors.OrderBy(static director => director.Source.Name, StringComparer.Ordinal)) {
			Gap();
			WriteMethod(writer, bound, new BoundMethod(director.Source.Name, director), "protected virtual");
		}
		if (bound.Directors.Count > 0) {
			Gap();
			WriteDirectorCallbacks(writer, bound);
		}
		foreach (BoundFunction constructor in bound.Constructors) {
			Gap();
			writer.Open($"private static {bound.Handle.InteropType}* CreateNative({ParameterList(constructor.ManagedParameters, withDefaults: false)})");
			// The thread is checked before anything is created, so a call on the wrong thread leaves nothing behind.
			writer.Line("Application.VerifyAccess();");
			if (bound.HasDirector) {
				for (BoundClass? declaring = bound; declaring is not null; declaring = declaring.Base) {
					if (declaring.Directors.Count > 0) writer.Line($"{declaring.Name}.Install{declaring.Name}Directors();");
				}
			}
			WriteCall(writer, constructor, self: null, result => $"return {result};");
			writer.Close();
		}
		writer.Close();
		return writer.ToString();
	}

	private static void WriteProperty(CodeWriter writer, BoundClass bound, BoundProperty property) {
		Summary(writer, property.Getter.Source.Brief);
		string type = property.Getter.Returns.ManagedReturnType(nullable: property.Getter.Returns is ObjectConversion or AnyObjectConversion);
		string modifiers = Modifiers(property.Getter, property.Hides);
		if (property.Setter is null && IsSimple(property.Getter)) {
			writer.Line($"{modifiers} {type} {property.Name} => {Call(bound, property.Getter, property.Getter.Returns.ManagedReturn)};");
			return;
		}
		writer.Open($"{modifiers} {type} {property.Name}");
		if (IsSimple(property.Getter)) {
			writer.Line($"get => {Call(bound, property.Getter, property.Getter.Returns.ManagedReturn)};");
		} else {
			writer.Open("get");
			WriteCall(writer, property.Getter, Self(bound, property.Getter), result => $"return {property.Getter.Returns.ManagedReturn(result)};");
			writer.Close();
		}
		if (property.Setter is BoundFunction setter) {
			// A value object set to null is set to its empty one, which for a window's font or cursor restores the default.
			BoundParameter value = setter.Parameters[0] with { Name = "value", Nullable = setter.Parameters[0].Nullable || setter.Parameters[0].Conversion is ValueConversion };
			BoundFunction renamed = new(setter.Owner, setter.Source, setter.Returns, [value], isConstructor: false) { ExportName = setter.ExportName };
			if (IsSimple(renamed)) {
				writer.Line($"set => {Call(bound, renamed, static result => result)};");
			} else {
				writer.Open("set");
				WriteCall(writer, renamed, Self(bound, renamed), static result => $"{result};");
				writer.Close();
			}
		}
		writer.Close();
	}

	private static void WriteMethod(CodeWriter writer, BoundClass bound, BoundMethod method, string? modifiers = null) {
		BoundFunction function = method.Function;
		Summary(writer, function.Source.Brief);
		string returns = function.Returns.ManagedReturnType(nullable: function.Returns is ObjectConversion or AnyObjectConversion);
		string signature = $"{modifiers ?? Modifiers(function, method.Hides)} {returns} {method.Name}({ParameterList(function.ManagedParameters, withDefaults: true)})";
		bool isVoid = function.Returns is VoidConversion;
		if (function.Returns is SelfConversion) {
			writer.Open(signature);
			WriteCall(writer, function, Self(bound, function), static result => $"{result};");
			writer.Line("return this;");
			writer.Close();
			return;
		}
		if (IsSimple(function)) {
			writer.Line($"{signature} => {Call(bound, function, function.Returns.ManagedReturn)};");
			return;
		}
		writer.Open(signature);
		WriteCall(writer, function, Self(bound, function), result => isVoid ? $"{result};" : $"return {function.Returns.ManagedReturn(result)};");
		writer.Close();
	}

	// The shim's director calls these, which call the managed object's override. When there is no
	// managed object yet, or any more, as while it is created or destroyed, they call wxWidgets's
	// own implementation. They are set once, before the first object of the class is created.
	private static void WriteDirectorCallbacks(CodeWriter writer, BoundClass bound) {
		foreach (BoundFunction director in bound.Directors.OrderBy(static director => director.Source.Name, StringComparer.Ordinal)) {
			IEnumerable<string> parameters = director.Parameters.Select(static parameter => $"{parameter.Conversion.InteropReturnType} {parameter.Name}").Prepend($"{bound.Handle.InteropType}* self");
			writer.Line("[global::System.Runtime.InteropServices.UnmanagedCallersOnly(CallConvs = [typeof(global::System.Runtime.CompilerServices.CallConvCdecl)])]");
			writer.Open($"private static {director.Returns.CallbackInteropType} Director{director.Source.Name}({string.Join(", ", parameters)})");
			writer.Open("try");
			string original = $"WxKitNative.{director.InteropName}({string.Join(", ", director.Parameters.Select(static parameter => parameter.Name).Prepend("self"))})";
			string call = $"owner.{director.Source.Name}({string.Join(", ", director.Parameters.Select(static parameter => parameter.Conversion.ManagedReturn(parameter.Name)))})";
			if (director.Returns is VoidConversion) {
				writer.Open($"if (ObjectRegistry.Find(self) is not {bound.Name} owner)");
				writer.Line($"{original};");
				writer.Line("return;");
				writer.Close();
				writer.Line($"{call};");
				writer.Continue("catch (Exception error)");
				writer.Line("Application.ReportException(error);");
			} else {
				writer.Line($"if (ObjectRegistry.Find(self) is not {bound.Name} owner) return {original};");
				writer.Line($"return {director.Returns.ToCallback(call)};");
				writer.Continue("catch (Exception error)");
				writer.Line("Application.ReportException(error);");
				writer.Line("return default;");
			}
			writer.Close();
			writer.Close();
			writer.Line();
		}
		writer.Line("private static bool _directorsInstalled;");
		writer.Line();
		writer.Open($"internal static void Install{bound.Name}Directors()");
		writer.Line("if (_directorsInstalled) return;");
		writer.Line("_directorsInstalled = true;");
		writer.Line($"WxKitNative.{Naming.Type(bound.CppName)}SetDirectors({string.Join(", ", bound.Directors.Select(static director => "&Director" + director.Source.Name))});");
		writer.Close();
	}

	private static string Modifiers(BoundFunction function, bool hides) => $"public{(hides ? " new" : string.Empty)}{(function.IsStatic ? " static" : string.Empty)}";

	// An instance member passes its object's handle. A static one has none.
	private static string? Self(BoundClass bound, BoundFunction function) => function.IsStatic ? null : bound.Handle.Accessor;

	// A call needs a block when a parameter has to be checked for null or pinned first, and a
	// static member always does, since only an instance member's handle checks the thread.
	private static bool IsSimple(BoundFunction function) => !function.IsStatic && function.Parameters.All(static parameter => parameter.Conversion.Check(parameter.Name, parameter.Nullable) is null && parameter.Conversion.Fixed(parameter.Name) is null && parameter.Conversion.Prepare(parameter.Name) is null && parameter.Conversion.Finish(parameter.Name) is null);

	private static string Call(BoundClass bound, BoundFunction function, Func<string, string> finish) => finish(InteropCall(function, Self(bound, function)));

	private static string InteropCall(BoundFunction function, string? self) {
		List<string> arguments = self is null ? [] : [self];
		arguments.AddRange(function.Parameters.SelectMany(static parameter => parameter.Conversion.InteropArguments(parameter.Name, parameter.Nullable)));
		return $"WxKitNative.{function.InteropName}({string.Join(", ", arguments)})";
	}

	private static void WriteCall(CodeWriter writer, BoundFunction function, string? self, Func<string, string> statement) {
		if (function.IsStatic) writer.Line("Application.VerifyAccess();");
		foreach (BoundParameter parameter in function.ManagedParameters) {
			if (parameter.Conversion.Check(parameter.Name, parameter.Nullable) is string check) writer.Line(check);
		}
		foreach (BoundParameter parameter in function.Parameters) {
			if (parameter.Conversion.Prepare(parameter.Name) is string prepare) writer.Line(prepare);
		}
		List<string> pins = [.. function.Parameters.Select(static parameter => parameter.Conversion.Fixed(parameter.Name)).OfType<string>()];
		List<string> finishes = [.. function.Parameters.Select(static parameter => parameter.Conversion.Finish(parameter.Name)).OfType<string>()];
		foreach (string pin in pins.SkipLast(1)) writer.Line(pin);
		if (pins.Count > 0) writer.Open(pins[^1]);
		if (finishes.Count == 0) {
			writer.Line(statement(InteropCall(function, self)));
		} else if (function.Returns is VoidConversion) {
			// What the call filled is read once it returns.
			writer.Line($"{InteropCall(function, self)};");
			foreach (string finish in finishes) writer.Line(finish);
		} else {
			writer.Line($"var returned = {InteropCall(function, self)};");
			foreach (string finish in finishes) writer.Line(finish);
			writer.Line(statement("returned"));
		}
		if (pins.Count > 0) writer.Close();
	}

	private static string ParameterList(IEnumerable<BoundParameter> parameters, bool withDefaults) => string.Join(", ", parameters.Select(parameter => {
		string declaration = $"{parameter.Conversion.ManagedType(parameter.Nullable)} {parameter.Name}";
		return withDefaults && parameter.Default is string value ? $"{declaration} = {value}" : declaration;
	}));

	private static string EventTypes(BindingResult result) {
		CodeWriter writer = Start();
		writer.Open("public static unsafe partial class EventType");
		bool first = true;
		// Each event type is made the first time it is used, in a class of its own, so an application
		// that never uses one never references its constant, and Native AOT leaves out the code
		// behind it, such as a data view's for wxEVT_DATAVIEW_SELECTION_CHANGED.
		foreach (BoundEventType type in result.EventTypes) {
			if (!first) writer.Line();
			first = false;
			Summary(writer, $"Wraps {type.Constant}.");
			writer.Line($"public static EventType<{type.EventClass.Name}> {type.Name} => {type.Name}Type.Value;");
			writer.Line();
			writer.Open($"private static class {type.Name}Type");
			writer.Line($"public static readonly EventType<{type.EventClass.Name}> Value = new(WxKitNative.EventType{type.Name}, static native => new {type.EventClass.Name}((WxkEvent*)native));");
			writer.Close();
		}
		writer.Close();
		return writer.ToString();
	}

	private static string Styles(BindingResult result) {
		CodeWriter writer = new CodeWriter().Line(Banner).Line().Line("namespace WxKit;");
		foreach (BoundClass bound in result.Classes) {
			if (bound.Styles is not BoundStyles styles) continue;
			writer.Line();
			Summary(writer, $"Styles for <see cref=\"{bound.Name}\"/>.", escape: false);
			writer.Line("[Flags]");
			writer.Open($"public enum {styles.Name} : long");
			foreach (BoundStyle style in styles.Members) {
				Summary(writer, style.Description.Length > 0 ? $"{Sentence(style.Description)}Wraps {style.Constant}." : $"Wraps {style.Constant}.");
				writer.Line(style.Value < 0 ? $"{style.Name} = {style.Value}," : $"{style.Name} = 0x{style.Value:X},");
			}
			writer.Close();
		}
		return writer.ToString();
	}

	// An enum whose values go where any int does, such as wxStandardID's window ids, as int constants.
	private static string ConstantClass(BoundEnum constants) {
		CodeWriter writer = new CodeWriter().Line(Banner).Line().Line("namespace WxKit;").Line();
		writer.Open($"public static partial class {constants.Name}");
		foreach (BoundStyle member in constants.Members) {
			Summary(writer, member.Description.Length > 0 ? $"{Sentence(member.Description)}Wraps {member.Constant}." : $"Wraps {member.Constant}.");
			// A mask with the top bit set, such as wxSTC_MASK_FOLDERS, keeps its bits as a negative int.
			string value = member.Value > int.MaxValue ? $"unchecked((int){member.Value}L)" : member.Value.ToString(System.Globalization.CultureInfo.InvariantCulture);
			writer.Line($"public const int {member.Name} = {value};");
		}
		writer.Close();
		return writer.ToString();
	}

	private static string Enums(BindingResult result) {
		CodeWriter writer = new CodeWriter().Line(Banner).Line().Line("namespace WxKit;");
		foreach (BoundEnum bound in result.Enums.Where(static bound => !bound.IsConstantClass)) {
			writer.Line();
			Summary(writer, $"Wraps {bound.CppName}.");
			if (bound.IsFlags) writer.Line("[Flags]");
			writer.Open($"public enum {bound.Name}");
			foreach (BoundStyle member in bound.Members) {
				Summary(writer, member.Description.Length > 0 ? $"{Sentence(member.Description)}Wraps {member.Constant}." : $"Wraps {member.Constant}.");
				// An enum crosses as a 32-bit int, so a value such as wxOBJID_SYSMENU, 0xFFFFFFFF, is -1.
				writer.Line($"{member.Name} = {(member.Value is > int.MaxValue and <= uint.MaxValue ? member.Value - (1L << 32) : member.Value)},");
			}
			writer.Close();
		}
		return writer.ToString();
	}

	// The art provider's ids, as constants: ArtId names an image, and ArtClient where it is shown.
	private static string ArtIds(BindingResult result) {
		CodeWriter writer = new CodeWriter().Line(Banner).Line().Line("namespace WxKit;");
		foreach ((string className, bool clients, string about) in new[] { ("ArtId", false, "The standard images ArtProvider gives."), ("ArtClient", true, "Where an ArtProvider image is shown, which can change which image it gives.") }) {
			writer.Line();
			Summary(writer, about);
			writer.Open($"public static class {className}");
			foreach ((string constant, string value) in result.StringConstants.Where(pair => pair.Value.EndsWith("_C", StringComparison.Ordinal) == clients).OrderBy(static pair => pair.Key, StringComparer.Ordinal)) {
				Summary(writer, $"Wraps {constant}.");
				writer.Line($"public const string {Naming.Words(constant["wxART_".Length..])} = \"{value}\";");
			}
			writer.Close();
		}
		return writer.ToString();
	}

	private static string Factories(BindingResult result) {
		CodeWriter writer = Start();
		writer.Open("internal static unsafe partial class ObjectRegistry");
		writer.Line("// The managed class to wrap each wxWidgets class in, for objects WxKit did not create.");
		writer.Line("private static readonly Dictionary<string, Func<nint, EvtHandler>> Factories = new(StringComparer.Ordinal) {");
		foreach (BoundClass bound in result.Classes.Where(static bound => bound.Handle.IsEvtHandler && (bound.Tweak.IsHandwritten ? bound.Tweak.IsWrappable : true))) {
			writer.Line($"\t[\"{bound.CppName}\"] = static native => new {bound.Name}(({bound.Handle.InteropType}*)native),");
		}
		writer.Line("};");
		writer.Close();
		return writer.ToString();
	}

	private static void Summary(CodeWriter writer, string text, bool escape = true) {
		if (text.Length == 0) return;
		writer.Line($"/// <summary>{(escape ? CodeWriter.Escape(text) : text)}</summary>");
	}

	// Ends a description with a full stop and a space, so a sentence can follow it.
	private static string Sentence(string text) {
		string trimmed = text.Trim();
		if (trimmed.Length == 0) return string.Empty;
		return trimmed.EndsWith('.') ? trimmed + " " : trimmed + ". ";
	}
}
